// Generated by scripts/gen_clock_fonts.py from the foundry's OFL faces
// (assets/fonts/): the time's digits in three sizes, the labels in two.
LV_FONT_DECLARE(fleet_clock_digits_80);
LV_FONT_DECLARE(fleet_clock_digits_104);
LV_FONT_DECLARE(fleet_clock_digits_132);
LV_FONT_DECLARE(fleet_clock_label_16);
LV_FONT_DECLARE(fleet_clock_label_22);

namespace {

const lv_font_t *const DIGITS[3] = { &fleet_clock_digits_80, &fleet_clock_digits_104, &fleet_clock_digits_132 };

// The C library's clock is set once TimeService has heard from SNTP; before
// that it counts from 1970.
constexpr time_t CLOCK_SET_AFTER = 1700000000;

// Setting the same text still redraws it: only what changed is set.
void setText(lv_obj_t *l, const char *t) {
    if (l && strcmp(lv_label_get_text(l), t)) lv_label_set_text(l, t);
}

lv_obj_t *rule(lv_obj_t *parent, uint32_t hex) {
    lv_obj_t *r = Kit::plain(parent);
    lv_obj_set_size(r, lv_pct(100), 1);
    lv_obj_set_style_bg_color(r, UI::c(hex), 0);
    lv_obj_set_style_bg_opa(r, LV_OPA_COVER, 0);
    return r;
}

} // namespace

ClockCard::~ClockCard() {
    if (_timer) lv_timer_delete(_timer);   // before Card's destructor takes the objects
}

void ClockCard::tickCb(lv_timer_t *t) {
    if (ClockCard *c = (ClockCard *)lv_timer_get_user_data(t)) c->render();
}

void ClockCard::buildBody(lv_obj_t *body) {
    const Clock::Palette &p = Clock::CLASSIC;
    // THE LARGEST SQUARE INSIDE THE CARD, from the page's sizes (the page is
    // not laid out yet). A pixel short of the body for its border.
    const int32_t pad = UI::sc(UI::met().PAD);
    const int32_t side = Clock::squareSide(surfaceWidthPx() - 2 * pad - 2,
                                           surfaceHeightPx() - bodyTopPx() - pad - 2);
    const int32_t inner = Clock::classicPad(side);

    _face = Kit::plain(body);
    lv_obj_set_size(_face, side, side);
    lv_obj_center(_face);
    lv_obj_set_style_radius(_face, UI::sc(UI::met().RADIUS), 0);
    lv_obj_set_style_bg_color(_face, UI::c(p.bg), 0);
    lv_obj_set_style_bg_opa(_face, LV_OPA_COVER, 0);
    lv_obj_set_style_pad_all(_face, inner, 0);
    lv_obj_set_flex_flow(_face, LV_FLEX_FLOW_COLUMN);
    lv_obj_set_flex_align(_face, LV_FLEX_ALIGN_SPACE_BETWEEN, LV_FLEX_ALIGN_START, LV_FLEX_ALIGN_START);

    // The labels' face: NINA's 27 px at 720, a little larger here - this
    // square is about half the size of NINA's on glass.
    const lv_font_t *lab = side >= 400 ? &fleet_clock_label_22 : &fleet_clock_label_16;
    const int32_t track = LV_MAX(1, side * 2 / 720);

    // The day, the date and the year, top left (NINA's header row; its right
    // half, the weather, comes later).
    lv_obj_t *head = Kit::plain(_face);
    lv_obj_set_size(head, lv_pct(100), LV_SIZE_CONTENT);
    lv_obj_set_flex_flow(head, LV_FLEX_FLOW_COLUMN);
    lv_obj_set_style_pad_row(head, LV_MAX(1, inner / 6), 0);
    lv_obj_t **heads[3] = { &_day, &_date, &_year };
    for (lv_obj_t **h : heads) {
        *h = Kit::label(head, lab, p.tertiary);
        lv_obj_set_style_text_letter_space(*h, track, 0);
    }

    rule(_face, p.rule);

    // The time over "A M": the largest digits whose "10:00" fits across.
    lv_obj_t *mid = Kit::plain(_face);
    lv_obj_set_width(mid, lv_pct(100));
    lv_obj_set_flex_grow(mid, 1);
    lv_obj_set_flex_flow(mid, LV_FLEX_FLOW_COLUMN);
    lv_obj_set_flex_align(mid, LV_FLEX_ALIGN_CENTER, LV_FLEX_ALIGN_CENTER, LV_FLEX_ALIGN_CENTER);
    int32_t widths[3];
    for (uint8_t i = 0; i < 3; i++) widths[i] = Kit::textW("10:00", DIGITS[i]);
    const lv_font_t *digits = DIGITS[Clock::pickFace(widths, 3, side - 2 * inner)];
    _time = Kit::label(mid, digits, p.primary);
    _ampm = Kit::label(mid, lab, p.dim);
    lv_obj_set_style_text_letter_space(_ampm, track + 1, 0);

    rule(_face, p.rule);

    _shown = -1;
    if (!_timer) _timer = lv_timer_create(tickCb, 1000, this);
}

void ClockCard::render() {
    if (!_time) return;
    const time_t now = time(nullptr);
    if (now < CLOCK_SET_AFTER) {   // not set yet: say so, without a wrong time
        if (_shown == -2) return;
        _shown = -2;
        setText(_time, "--:--");
        setText(_ampm, "");
        setText(_day, "");
        setText(_date, "");
        setText(_year, "");
        return;
    }
    struct tm t;
    localtime_r(&now, &t);
    const int32_t minute = t.tm_yday * 1440 + t.tm_hour * 60 + t.tm_min;
    if (minute == _shown) return;
    _shown = minute;
    char buf[24];
    Clock::timeText(buf, sizeof(buf), t.tm_hour, t.tm_min, false);
    setText(_time, buf);
    setText(_ampm, Clock::meridiem(t.tm_hour, false));
    setText(_day, Clock::weekdayName(t.tm_wday));
    Clock::dateText(buf, sizeof(buf), t.tm_mon, t.tm_mday);
    setText(_date, buf);
    snprintf(buf, sizeof(buf), "%d", t.tm_year + 1900);
    setText(_year, buf);
}
