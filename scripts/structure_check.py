#!/usr/bin/env python3
"""The structure check (2.12 P6): what the UI's layers say should not happen, counted.

It REPORTS; it never fails a build. Run it with the all-nine gate before a merge and quote what it
prints in the merge report - the card window grew to 6,325 lines in one file, and a check like
this would have said so at 1,000.

    python scripts/structure_check.py              # the report
    python scripts/structure_check.py --max 800    # a tighter line limit

What it looks for, in src/ and include/ (the firmware's own code; components/ are libraries):

  1. a source file over --max lines (default 1,000);
  2. lv_obj_set_style_* outside the component kit (src/UI/Kit/) - the kit owns how things look
     (CLAUDE.md, "The component kit"); the rest should use a role. Counted per file;
  3. a colour literal (0xRRGGBB, lv_color_hex) outside the tokens (src/UI/UITokens.cpp);
  4. a number where a shape token belongs: mm(1.6f) / pm(4) in the card window, a radius set to a
     number (CLAUDE.md, "The card window's sizes are UIShape millimetres");
  5. LVGL in SystemCore or SystemReport, which must stay UI-free (CLAUDE.md, "Application layout").

Standard library only.
"""

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SCAN = ("src", "include")
EXTS = {".c", ".cpp", ".h", ".hpp"}

KIT = "src/UI/Kit/"
TOKENS = ("src/UI/UITokens.cpp",)
# Colours that are deliberately not tokens, each with its reason in the code:
COLOUR_OK = {
    "src/UI/Kit/KitSparks.cpp",   # the colours of electricity, the same on every scheme
}
# Not the firmware's own hand-written code - generated by the project's scripts (the font faces,
# the icon and type tables, the version stamp), vendored, or LVGL's own config template. Skipped by
# every check, and counted in the report so nothing hides there.
SKIP_DIRS = ("src/UI/fonts/", "include/third_party/")
SKIP_FILES = ("include/UI/UIIcons.h", "include/UI/UITypeScale.h", "include/fleet_fw_version.h",
              "include/lvgl/lv_conf.h")

STYLE_RE = re.compile(r"\blv_obj_set_style_\w+\s*\(")
HEX_RE = re.compile(r"(?<!&)(?<!& )\b0x[0-9A-Fa-f]{6}\b")   # not a mask: x & 0xFFFFFF
LVHEX_RE = re.compile(r"\blv_color_hex\s*\(")
MM_RE = re.compile(r"\b[mp]m\(\s*[0-9.]+f?\s*\)")
RADIUS_RE = re.compile(r"lv_obj_set_style_radius\s*\([^,]+,\s*([0-9]+)\s*,")
LVGL_RE = re.compile(r'#\s*include\s*[<"](lvgl|src/core|src/misc|lv_)[^>"]*[>"]')


def strip_comments(text):
    """Code without // and /* */ comments or string contents, so a literal in a comment or a
    message is not counted. Lines are kept, so line numbers stay true."""
    out, i, n = [], 0, len(text)
    while i < n:
        c = text[i]
        if text.startswith("//", i):
            while i < n and text[i] != "\n":
                i += 1
        elif text.startswith("/*", i):
            j = text.find("*/", i + 2)
            j = n if j < 0 else j + 2
            out.append("".join(ch for ch in text[i:j] if ch == "\n"))
            i = j
        elif c in "\"'":
            q = c
            out.append(q)
            i += 1
            while i < n and text[i] != q:
                if text[i] == "\\":
                    i += 1
                elif text[i] == "\n":
                    break
                i += 1
            out.append(q)
            i += 1
        else:
            out.append(c)
            i += 1
    return "".join(out)


def files():
    for d in SCAN:
        for p in sorted((ROOT / d).rglob("*")):
            if p.suffix in EXTS and p.is_file():
                yield p, p.relative_to(ROOT).as_posix()


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--max", type=int, default=1000, help="lines a file may have (default 1000)")
    args = ap.parse_args()
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")
        except (AttributeError, ValueError):
            pass

    big, styles, colours, shapes, layers = [], [], [], [], []
    skipped = 0
    for path, rel in files():
        if rel.startswith(SKIP_DIRS) or rel in SKIP_FILES:
            skipped += 1
            continue
        raw = path.read_text(encoding="utf-8", errors="replace")
        lines = raw.count("\n") + 1
        if lines > args.max:
            big.append((rel, lines))
        code = strip_comments(raw)
        n_style = len(STYLE_RE.findall(code))
        if n_style and not rel.startswith(KIT):
            styles.append((rel, n_style))
        if rel not in TOKENS and rel not in COLOUR_OK:
            n_col = len(HEX_RE.findall(code)) + len(LVHEX_RE.findall(code))
            if n_col:
                colours.append((rel, n_col))
        hits = []
        for ln, line in enumerate(code.splitlines(), 1):
            if MM_RE.search(line):
                hits.append(f"{ln}: {MM_RE.search(line).group(0)}")
            m = RADIUS_RE.search(line)
            if m and m.group(1) != "0":
                hits.append(f"{ln}: radius {m.group(1)}")
        if hits:
            shapes.append((rel, hits))
        if re.search(r"(^|/)System(Core|Report)\.(cpp|h)$", rel) and LVGL_RE.search(code):
            layers.append(rel)

    print("STRUCTURE CHECK (scripts/structure_check.py - reports, never fails)")
    print(f"src/ and include/; {skipped} generated or vendored files skipped "
          "(src/UI/fonts/, include/third_party/, lv_conf.h, the generated headers)")
    print()
    print(f"1. Files over {args.max} lines: {len(big) or 'none'}")
    for rel, n in sorted(big, key=lambda x: -x[1]):
        print(f"     {n:6d}  {rel}")
    print()
    total = sum(n for _, n in styles)
    print(f"2. lv_obj_set_style_* outside the kit ({KIT}): {total} in {len(styles)} files")
    for rel, n in sorted(styles, key=lambda x: -x[1]):
        print(f"     {n:6d}  {rel}")
    print()
    total = sum(n for _, n in colours)
    print(f"3. Colour literals outside the tokens: {total} in {len(colours)} files")
    for rel, n in sorted(colours, key=lambda x: -x[1]):
        print(f"     {n:6d}  {rel}")
    print()
    total = sum(len(h) for _, h in shapes)
    print(f"4. Numbers where a shape token belongs (mm()/pm() literals, numeric radii): {total or 'none'}")
    for rel, hits in shapes:
        print(f"     {rel}")
        for h in hits[:8]:
            print(f"         {h}")
        if len(hits) > 8:
            print(f"         ... and {len(hits) - 8} more")
    print()
    print(f"5. LVGL included in SystemCore / SystemReport: {', '.join(layers) if layers else 'none'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
